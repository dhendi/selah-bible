export const SEARCH_STARTER_CHIPS = [
  'Faith & Love',
  'Courage for Kids',
  'Forgiveness',
  'Trusting God',
];

export function searchStoryModules(query: string): StoryModule[] {
  const q = query.trim().toLowerCase();
  if (!q) return SEED_STORY_MODULES;

  const stopWords = new Set(['give', 'me', 'a', 'story', 'stories', 'about', 'for', 'the', 'and', 'with', 'in', 'to', 'of', 'find']);
  const tokens = q
    .replace(/[^\w\s]/g, ' ')
    .split(/\s+/)
    .filter((w) => w.length > 1 && !stopWords.has(w));

  if (tokens.length === 0) return SEED_STORY_MODULES;

  const scored = SEED_STORY_MODULES.map((mod) => {
    let score = 0;
    const haystack = [
      mod.title,
      mod.subtitle,
      mod.bigPictureSummary,
      mod.anchorVerseText,
      mod.chapterRange,
      ...mod.themes,
    ]
      .join(' ')
      .toLowerCase();

    if (haystack.includes(q)) score += 10;

    tokens.forEach((token) => {
      if (mod.themes.some((t) => t.includes(token))) score += 5;
      if (mod.title.toLowerCase().includes(token)) score += 4;
      if (haystack.includes(token)) score += 2;
      if ((token === 'kid' || token === 'kids' || token === 'children' || token === 'family') && mod.kidFriendly) {
        score += 4;
      }
    });

    return { mod, score };
  });

  const matching = scored.filter((item) => item.score > 0).sort((a, b) => b.score - a.score);
  return matching.length > 0 ? matching.map((m) => m.mod) : SEED_STORY_MODULES;
}
