export interface ResolvedEntityAsset {
  src: string;
  alt: string;
  isPortrait: boolean;
}

export function resolveEntityAsset({
  type,
  iconSlug,
  entityId,
  characterId,
  title,
}: {
  type: string;
  iconSlug?: string;
  entityId?: string;
  characterId?: string;
  title?: string;
}): ResolvedEntityAsset {
  let src = '/images/wisdom-scroll.webp';
  let isPortrait = false;
  let alt = title ? `${title} illustration` : 'Biblical context artwork';

  if (characterId && SEED_CHARACTERS[characterId]) {
    const portrait = getPortraitAsset(SEED_CHARACTERS[characterId].portraitIllustrationId);
    if (portrait) {
      src = portrait.src;
      alt = title ? `${title} portrait` : portrait.alt;
      isPortrait = true;
    }
  } else if (entityId && ENTITY_SCENE_MAP[entityId]) {
    src = ENTITY_SCENE_MAP[entityId];
    isPortrait = src.includes('/portrait-');
  } else if (iconSlug === 'manna-flakes' || iconSlug === 'dew-frost' || iconSlug === 'quail-bird' || iconSlug === 'bread-loaf') {
    src = '/images/exo-16.webp';
  } else if (iconSlug === 'moses-staff') {
    src = '/images/portrait-moses.webp';
    isPortrait = true;
  } else if (iconSlug === 'wheat-grain') {
    src = '/images/gen-04.webp';
  } else if (iconSlug === 'peace-dove') {
    src = '/images/gen-08.webp';
  } else if (iconSlug === 'water-spring') {
    src = '/images/gen-16.webp';
  } else if (iconSlug === 'divine-light' || iconSlug === 'cosmic-spark' || iconSlug === 'spark-beginning' || iconSlug === 'stars-sky') {
    src = '/images/gen-01.webp';
  } else if (iconSlug === 'earth-globe') {
    src = '/images/peace-pastures.webp';
  } else if (iconSlug === 'covenant-fire') {
    src = '/images/courage-light.webp';
  } else if (iconSlug === 'desert-dunes' || type === 'place') {
    src = '/images/ruth-naomi.webp';
  } else if (type === 'person') {
    src = '/images/portrait-ruth.webp';
    isPortrait = true;
  }

  return { src, alt, isPortrait };
}

export const EntityThumbnail: React.FC<{
  type: string;
  iconSlug?: string;
  entityId?: string;
  characterId?: string;
  className?: string;
}> = ({ type, iconSlug, entityId, characterId, className = 'w-12 h-12' }) => {
  const { src, alt } = resolveEntityAsset({ type, iconSlug, entityId, characterId });

  return (
    <div className={`rounded-xl bg-[#F3EFE6] border border-[#E5DFD5] shadow-sm overflow-hidden flex-shrink-0 ${className}`}>
      <img
        src={assetUrl(src)}
        alt={alt}
        className="w-full h-full object-cover object-top"
        loading="lazy"
      />
    </div>
  );
};
